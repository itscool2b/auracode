// Writes src/graphite/creaturePaths.ts from the drawings in src/graphite/creatureGeometry.ts.
// Run after changing a creature: node packages/ui/scripts/creature-paths.ts
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  buildCreaturePaths,
  CREATURE_GAPS,
  SEAL_SPEC,
  TURTLE_SPEC,
} from "../src/graphite/creatureGeometry.ts";

const built = buildCreaturePaths();

/** Splits a path into lines of whole commands, each under the formatter's width. */
function chunks(d: string): string {
  const commands = d.match(/[MCZ][^MCZ]*/g) ?? [];
  const lines: string[] = [];
  let line = "";
  for (const command of commands) {
    if (line && line.length + command.length > 88) {
      lines.push(line);
      line = "";
    }
    line += command;
  }
  if (line) lines.push(line);
  return lines.map((part) => `  "${part}"`).join(" +\n");
}

const source = `/**
 * The seal and the sea turtle that swim through Shallows (docs/design/visual-language.md 4.16):
 * flat silhouettes in the logo's language, a body with its flippers set off by even gaps and one
 * eye hole, each one even-odd path of absolute M, C and Z commands.
 *
 * Generated by packages/ui/scripts/creature-paths.ts from creatureGeometry.ts. Do not edit by hand.
 */

/** A harbour seal from the side, swimming right. */
export const SEAL_VIEWBOX = [${SEAL_SPEC.viewBox.join(", ")}] as const;

/** The seal for drawings wider than CREATURE_SMALL_MAX px (gap ${CREATURE_GAPS.seal}). */
export const SEAL_PATH =
${chunks(built.seal.path)};

/** The seal for drawings up to CREATURE_SMALL_MAX px: wider gaps, a larger eye (gap ${CREATURE_GAPS.sealSmall}). */
export const SEAL_SMALL_PATH =
${chunks(built.sealSmall.path)};

/** A sea turtle seen from below, swimming right. */
export const TURTLE_VIEWBOX = [${TURTLE_SPEC.viewBox.join(", ")}] as const;

/** The turtle for drawings wider than CREATURE_SMALL_MAX px (gap ${CREATURE_GAPS.turtle}). */
export const TURTLE_PATH =
${chunks(built.turtle.path)};

/** The turtle for drawings up to CREATURE_SMALL_MAX px: wider gaps (gap ${CREATURE_GAPS.turtleSmall}). */
export const TURTLE_SMALL_PATH =
${chunks(built.turtleSmall.path)};

/** Drawings this wide or narrower use the small variants, whose gaps stay open. */
export const CREATURE_SMALL_MAX = 64;
`;

writeFileSync(fileURLToPath(new URL("../src/graphite/creaturePaths.ts", import.meta.url)), source);
