/** The jet the last launch showed, so the next one shows another. */
const LAST_JET_KEY = "auracode.newChat.jet";

type JetStorage = Pick<Storage, "getItem" | "setItem">;

function deviceStorage(): JetStorage | null {
  try {
    return typeof localStorage === "undefined" ? null : localStorage;
  } catch {
    return null;
  }
}

/**
 * A jet other than the one `storage` says the last launch showed, remembered for the next. Storage
 * that cannot be read or written only loses the "never twice in a row" promise.
 */
export function pickJet(
  random: () => number = Math.random,
  storage: JetStorage | null = deviceStorage(),
): Jet {
  let last: string | null = null;
  try {
    last = storage?.getItem(LAST_JET_KEY) ?? null;
  } catch {}
  const choices = JETS.filter((jet) => jet.name !== last);
  const jet = choices[Math.min(choices.length - 1, Math.floor(random() * choices.length))] as Jet;
  try {
    storage?.setItem(LAST_JET_KEY, jet.name);
  } catch {}
  return jet;
}

let launchJet: Jet | null = null;

/** This launch's jet: chosen once, so New chat shows the same one until auracode starts again. */
export function bootJet(): Jet {
  launchJet ??= pickJet();
  return launchJet;
}
